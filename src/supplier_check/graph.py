logger = logging.getLogger(__name__)


class HumanResolution(TypedDict, total=False):
    """Payload provided when resuming a human review interrupt."""

    decision: str  # "Approve" or "Reject"
    reviewer_note: str


class PipelineReport(TypedDict):
    """Structured result generated by the report node."""

    pdf: str
    supplier: str
    item: str
    system_verdict: str
    final_verdict: str
    reviewer_note: str | None
    extractor_used: str
    triggered_rules: list[dict[str, str]]
    audit_log: list[str]


class PipelineState(TypedDict, total=False):
    """State carried through the fixed linear LangGraph pipeline."""

    pdf_path: str
    raw_text: str
    pr_items: list[PurchaseRequestItem]
    pr_csv_path: str | None
    extracted_quote: ExtractedQuote | None
    extractor_used: str
    grounding_errors: list[str]
    rule_results: list[RuleResult]
    decision: Decision | None
    human_resolution: HumanResolution | None
    report: PipelineReport | None
    audit_log: list[str]
    config: RulesConfig
    llm_client: LLMClient | None
    extractor_mode: str  # auto, fallback, llm, both


def _log_event(state: PipelineState, message: str) -> None:
    """Append a timestamped log entry to the state's audit log."""
    ts = datetime.datetime.now(datetime.UTC).isoformat()
    entry = f"[{ts}] {message}"
    if "audit_log" not in state or state["audit_log"] is None:
        state["audit_log"] = []
    state["audit_log"].append(entry)
    logger.info(entry)


def _load_default_pr_items(csv_path: str | Path | None = None) -> list[PurchaseRequestItem]:
    """Load PR items from data/purchase-request.csv or provided path."""
    target_path = Path(csv_path or "data/purchase-request.csv")
    if not target_path.exists():
        return []
    with target_path.open(encoding="utf-8-sig") as f:
        rows = list(csv.DictReader(f))
    items: list[PurchaseRequestItem] = []
    for r in rows:
        items.append(
            PurchaseRequestItem(
                pr_number=r.get("PR number", ""),
                item_code=r.get("Item", ""),
                description=r.get("Description", ""),
                quantity_requested=Decimal(r.get("Quantity requested", "0")),
                unit=r.get("Unit", ""),
                max_unit_price=Decimal(r.get("Maximum unit price (BDT)", "0")),
            )
        )
    return items


# ---------------------------------------------------------------------------
# Node 1: Ingest
# ---------------------------------------------------------------------------


def node_ingest(state: PipelineState) -> dict[str, Any]:
    """Read the PDF text and ensure PR items are loaded."""
    pdf_path_str = state.get("pdf_path", "")
    _log_event(state, f"Starting ingest for: {pdf_path_str}")

    pr_items = state.get("pr_items")
    if not pr_items:
        pr_csv_path = state.get("pr_csv_path")
        try:
            pr_items = _load_default_pr_items(pr_csv_path)
        except Exception as e:
            _log_event(state, f"Failed to load PR items: {e}")
            pr_items = []

    # If raw_text is explicitly provided in state (e.g. for synthetic tests), preserve it
    if "raw_text" in state and state["raw_text"] is not None:
        raw_val = state["raw_text"]
        if not raw_val.strip():
            msg = "PDF text is empty or unreadable"
            _log_event(state, msg)
            return {
                "raw_text": "",
                "pr_items": pr_items,
                "grounding_errors": [msg],
                "audit_log": state["audit_log"],
            }
        _log_event(state, f"Using provided raw_text ({len(raw_val)} chars)")
        return {
            "raw_text": raw_val,
            "pr_items": pr_items,
            "grounding_errors": state.get("grounding_errors", []),
            "audit_log": state["audit_log"],
        }

    if not pdf_path_str:
        _log_event(state, "No pdf_path provided in state.")
        return {
            "raw_text": "",
            "pr_items": pr_items,
            "grounding_errors": ["Missing pdf_path"],
            "audit_log": state["audit_log"],
        }

    path = Path(pdf_path_str)
    if not path.exists():
        msg = f"PDF file does not exist: {pdf_path_str}"
        _log_event(state, msg)
        return {
            "raw_text": "",
            "pr_items": pr_items,
            "grounding_errors": [msg],
            "audit_log": state["audit_log"],
        }

    try:
        reader = PdfReader(str(path))
        text = "\n".join(page.extract_text() or "" for page in reader.pages)
        if not text.strip():
            msg = f"PDF text is empty or unreadable: {pdf_path_str}"
            _log_event(state, msg)
            return {
                "raw_text": "",
                "pr_items": pr_items,
                "grounding_errors": [msg],
                "audit_log": state["audit_log"],
            }
        _log_event(state, f"Ingested {len(text)} characters from {path.name}")
        return {
            "raw_text": text,
            "pr_items": pr_items,
            "grounding_errors": state.get("grounding_errors", []),
            "audit_log": state["audit_log"],
        }
    except Exception as e:
        msg = f"Exception ingesting PDF: {e}"
        _log_event(state, msg)
        return {
            "raw_text": "",
            "pr_items": pr_items,
            "grounding_errors": [msg],
            "audit_log": state["audit_log"],
        }


# ---------------------------------------------------------------------------
# Node 2: Extract
# ---------------------------------------------------------------------------


def node_extract(state: PipelineState) -> dict[str, Any]:
    """Extract quote fields according to extractor mode."""
    raw_text = state.get("raw_text", "")
    grounding_errors = list(state.get("grounding_errors") or [])

    if not raw_text.strip():
        _log_event(state, "Skipping extraction: raw_text is empty")
        return {
            "extracted_quote": None,
            "extractor_used": "none",
            "audit_log": state["audit_log"],
        }

    mode = state.get("extractor_mode") or os.getenv("EXTRACTOR", "auto").lower()
    has_api_key = bool(os.getenv("GEMINI_API_KEY"))

    llm_client = state.get("llm_client")
    if llm_client is None and has_api_key:
        try:
            llm_client = GeminiClient()
        except Exception as e:
            _log_event(state, f"Failed to initialize GeminiClient: {e}")
            llm_client = None

    # Resolve mode 'auto'
    resolved_mode = mode
    if mode == "auto":
        resolved_mode = "both" if (llm_client is not None or has_api_key) else "fallback"
        _log_event(
            state,
            f"Resolved auto mode to: {resolved_mode} (has_llm={llm_client is not None}, has_key={has_api_key})",
        )

    extracted_quote: ExtractedQuote | None = None
    extractor_used = resolved_mode

    try:
        if resolved_mode == "fallback":
            if not has_api_key and (mode == "auto" or resolved_mode == "fallback"):
                _log_event(state, "LLM not run: no API key")
                extractor_used = "fallback only (no key)"
            else:
                extractor_used = "fallback only"
            extracted_quote = extract_fallback_from_text(raw_text)
            _log_event(state, f"Extracted using fallback extractor ({extractor_used}).")

        elif resolved_mode == "llm":
            if llm_client is None:
                if not has_api_key:
                    _log_event(state, "LLM not run: no API key")
                    extractor_used = "fallback only (no key)"
                else:
                    _log_event(state, "LLM client requested but unavailable; falling back.")
                    extractor_used = "fallback only (LLM failed)"
                extracted_quote = extract_fallback_from_text(raw_text)
            else:
                try:
                    quote = _extract_with_retry(llm_client, raw_text, state)
                    extracted_quote = quote
                    extractor_used = "gemini only"
                    _log_event(state, "Extracted using LLM.")
                except Exception as e:
                    _log_event(state, f"LLM failed: {e}; fallback used")
                    extracted_quote = extract_fallback_from_text(raw_text)
                    extractor_used = "fallback only (LLM failed)"

        elif resolved_mode == "both":
            fb_quote = extract_fallback_from_text(raw_text)
            if llm_client is None:
                if not has_api_key:
                    _log_event(state, "LLM not run: no API key")
                    extractor_used = "fallback only (no key)"
                else:
                    _log_event(state, "LLM client unavailable; fallback used")
                    extractor_used = "fallback only (LLM failed)"
                extracted_quote = fb_quote
            else:
                try:
                    llm_quote = _extract_with_retry(llm_client, raw_text, state)
                    reconciled, notes, disagreements = reconcile_quotes_with_count(
                        llm_quote, fb_quote
                    )
                    for n in notes:
                        _log_event(state, f"Reconcile note: {n}")
                    extracted_quote = reconciled
                    if disagreements == 0:
                        extractor_used = "gemini+fallback (agreed)"
                    else:
                        extractor_used = f"gemini+fallback ({disagreements} fields disagreed)"
                    _log_event(
                        state,
                        f"Successfully reconciled LLM and fallback extractions ({extractor_used}).",
                    )
                except Exception as e:
                    _log_event(state, f"LLM failed: {e}; fallback used")
                    extracted_quote = fb_quote
                    extractor_used = "fallback only (LLM failed)"
        else:
            _log_event(state, f"Unknown extractor mode '{mode}', defaulting to fallback.")
            extracted_quote = extract_fallback_from_text(raw_text)
            extractor_used = "fallback only"

    except Exception as e:
        msg = f"Fatal extraction exception: {e}"
        _log_event(state, msg)
        grounding_errors.append(msg)
        extracted_quote = None
        extractor_used = "failed"

    return {
        "extracted_quote": extracted_quote,
        "extractor_used": extractor_used,
        "grounding_errors": grounding_errors,
        "audit_log": state["audit_log"],
    }


def _extract_with_retry(client: LLMClient, raw_text: str, state: PipelineState) -> ExtractedQuote:
    """Attempt LLM extraction with 1 retry on invalid output."""
    last_err: Exception | None = None
    for attempt in range(2):
        try:
            raw_dict = client.extract(raw_text)
            flat = FlatLLMQuote.model_validate(raw_dict)
            return map_flat_to_extracted_quote(flat, raw_text, audit_log=state.get("audit_log"))
        except Exception as e:
            last_err = e
            _log_event(state, f"LLM attempt {attempt + 1} error: {e}")
    if last_err:
        raise last_err
    raise RuntimeError("LLM extraction failed with empty response")


# ---------------------------------------------------------------------------
# Node 3: Verify
# ---------------------------------------------------------------------------


def node_verify(state: PipelineState) -> dict[str, Any]:
    """Verify evidence quotes against document text."""
    quote = state.get("extracted_quote")
    raw_text = state.get("raw_text", "")
    grounding_errors = list(state.get("grounding_errors") or [])

    if quote is None:
        _log_event(state, "Skipping verify: extracted_quote is None")
        return {"grounding_errors": grounding_errors, "audit_log": state.get("audit_log", [])}

    try:
        verified_quote = verify_and_ground_quote(quote, raw_text)
        # Check if any grounding failure occurred on decision fields
        for field_name in [
            "unit_price",
            "quantity",
            "total",
            "advance_percent",
            "payment_days",
            "delivery_days",
            "validity_days",
        ]:
            fe = getattr(verified_quote, field_name)
            if not fe.grounded:
                note = f"Grounding check failed for {field_name}: evidence quote not in document"
                grounding_errors.append(note)
                _log_event(state, note)

        return {
            "extracted_quote": verified_quote,
            "grounding_errors": grounding_errors,
            "audit_log": state.get("audit_log", []),
        }
    except Exception as e:
        msg = f"Exception in verify node: {e}"
        _log_event(state, msg)
        grounding_errors.append(msg)
        return {
            "grounding_errors": grounding_errors,
            "audit_log": state.get("audit_log", []),
        }


# ---------------------------------------------------------------------------
# Node 4: Compare
# ---------------------------------------------------------------------------


def node_compare(state: PipelineState) -> dict[str, Any]:
    """Match quote with PR items and run price/quantity comparisons."""
    quote = state.get("extracted_quote")
    pr_items = state.get("pr_items") or []
    config = state.get("config") or RulesConfig.from_yaml("config/rules.yaml")
    results = list(state.get("rule_results") or [])

    if quote is None or not pr_items:
        _log_event(state, "Skipping compare: extracted_quote or pr_items is missing")
        return {"rule_results": results, "audit_log": state.get("audit_log", [])}

    try:
        matched_pr, comp_results = run_pr_comparisons(quote, pr_items, config)
        results.extend(comp_results)
        _log_event(
            state,
            f"Compare completed: matched_pr={matched_pr.item_code if matched_pr else None}, results={len(comp_results)}",
        )
        return {
            "rule_results": results,
            "audit_log": state.get("audit_log", []),
        }
    except Exception as e:
        msg = f"Exception in compare node: {e}"
        _log_event(state, msg)
        results.append(
            RuleResult(
                rule_id="RULE_REV_11_UNVERIFIABLE_FIELD",
                severity=Severity.REVIEW,
                message=msg,
                evidence_quote="N/A",
            )
        )
        return {
            "rule_results": results,
            "audit_log": state.get("audit_log", []),
        }


# ---------------------------------------------------------------------------
# Node 5: Rules
# ---------------------------------------------------------------------------


def node_rules(state: PipelineState) -> dict[str, Any]:
    """Execute all deterministic procurement policy rules."""
    quote = state.get("extracted_quote")
    config = state.get("config") or RulesConfig.from_yaml("config/rules.yaml")
    results = list(state.get("rule_results") or [])

    if quote is None:
        _log_event(state, "Skipping rules: extracted_quote is None")
        results.append(
            RuleResult(
                rule_id="RULE_REV_11_UNVERIFIABLE_FIELD",
                severity=Severity.REVIEW,
                message="Extracted quote is missing or extraction failed",
                evidence_quote="N/A",
            )
        )
        return {"rule_results": results, "audit_log": state.get("audit_log", [])}

    try:
        policy_results = run_all_policy_rules(
            quote, config, raw_document_text=state.get("raw_text")
        )
        results.extend(policy_results)
        _log_event(state, f"Rules completed: evaluated {len(policy_results)} policy rules.")
        return {
            "rule_results": results,
            "audit_log": state.get("audit_log", []),
        }
    except Exception as e:
        msg = f"Exception in rules node: {e}"
        _log_event(state, msg)
        results.append(
            RuleResult(
                rule_id="RULE_REV_11_UNVERIFIABLE_FIELD",
                severity=Severity.REVIEW,
                message=msg,
                evidence_quote="N/A",
            )
        )
        return {
            "rule_results": results,
            "audit_log": state.get("audit_log", []),
        }


# ---------------------------------------------------------------------------
# Node 6: Decide
# ---------------------------------------------------------------------------


def node_decide(state: PipelineState) -> dict[str, Any]:
    """Aggregate rule results and grounding errors into a system verdict."""
    rule_results = state.get("rule_results") or []
    grounding_errors = state.get("grounding_errors") or []

    try:
        decision = make_decision(rule_results, grounding_errors=grounding_errors)
        _log_event(
            state, f"Decision made: {decision.verdict.value} (display: {decision.display_verdict})"
        )

        # Pre-populate report so interrupted states also have a valid report structure
        preliminary_report = _build_report_payload(state, decision=decision)

        return {
            "decision": decision,
            "report": preliminary_report,
            "audit_log": state.get("audit_log", []),
        }
    except Exception as e:
        msg = f"Exception in decide node: {e}"
        _log_event(state, msg)
        fallback_decision = Decision(
            verdict=Verdict.NEEDS_REVIEW,
            triggered_rules=[
                RuleResult(
                    rule_id="RULE_REV_11_UNVERIFIABLE_FIELD",
                    severity=Severity.REVIEW,
                    message=msg,
                    evidence_quote="N/A",
                )
            ],
            reasons=[msg],
        )
        preliminary_report = _build_report_payload(state, decision=fallback_decision)
        return {
            "decision": fallback_decision,
            "report": preliminary_report,
            "audit_log": state.get("audit_log", []),
        }


# ---------------------------------------------------------------------------
# Conditional Edge: decide -> human_review or report
# ---------------------------------------------------------------------------


def route_after_decide(state: PipelineState) -> Literal["human_review", "report"]:
    """Route to human_review if verdict is NEEDS_REVIEW, otherwise directly to report."""
    decision = state.get("decision")
    if decision and decision.verdict == Verdict.NEEDS_REVIEW:
        return "human_review"
    return "report"


# ---------------------------------------------------------------------------
# Node 7: Human Review (interruptible)
# ---------------------------------------------------------------------------


def node_human_review(state: PipelineState) -> dict[str, Any]:
    """Pause execution via interrupt() to allow human reviewer input."""
    decision = state.get("decision")
    triggered = decision.triggered_rules if decision else []
    payload = {
        "pdf_path": state.get("pdf_path"),
        "system_verdict": decision.display_verdict if decision else "Needs a person to check",
        "reasons": decision.reasons if decision else [],
        "triggered_rules": [
            {
                "rule_id": r.rule_id,
                "severity": r.severity.value,
                "message": r.message,
                "evidence_quote": r.evidence_quote,
            }
            for r in triggered
        ],
    }

    _log_event(state, "Pausing for human review via interrupt().")
    resolution = interrupt(payload)

    # Resumed: resolution should be dict with decision and reviewer_note
    res_dict: HumanResolution = {}
    if isinstance(resolution, dict):
        res_dict = {
            "decision": str(resolution.get("decision", "Needs a person to check")),
            "reviewer_note": str(resolution.get("reviewer_note", "")),
        }
    else:
        res_dict = {
            "decision": str(resolution),
            "reviewer_note": "",
        }

    _log_event(
        state,
        f"Human review resumed with decision: '{res_dict.get('decision')}', note: '{res_dict.get('reviewer_note')}'",
    )
    return {
        "human_resolution": res_dict,
        "audit_log": state.get("audit_log", []),
    }


# ---------------------------------------------------------------------------
# Node 8: Report
# ---------------------------------------------------------------------------


def _build_report_payload(
    state: PipelineState,
    decision: Decision | None = None,
    resolution: HumanResolution | None = None,
) -> PipelineReport:
    """Build structured report preserving system verdict and recording reviewer resolution."""
    dec = decision or state.get("decision")
    quote = state.get("extracted_quote")
    pdf_path = state.get("pdf_path", "unknown")
    res = resolution or state.get("human_resolution")

    system_verdict = dec.display_verdict if dec else "Needs a person to check"
    final_verdict = system_verdict
    reviewer_note: str | None = None

    if res:
        rev_dec = res.get("decision")
        if rev_dec:
            final_verdict = rev_dec
        reviewer_note = res.get("reviewer_note")

    supplier_name = "Unknown"
    item_code = "Unknown"
    if quote:
        if quote.supplier_name.value:
            supplier_name = str(quote.supplier_name.value)
        if quote.item_code.value:
            item_code = str(quote.item_code.value)

    if supplier_name == "Unknown":
        # Check audit log if extraction had an error or fallback had supplier
        fb_supp = None
        raw_text = state.get("raw_text", "")
        if raw_text:
            try:
                fb_q = extract_fallback_from_text(raw_text)
                if fb_q and fb_q.supplier_name and fb_q.supplier_name.value:
                    fb_supp = str(fb_q.supplier_name.value)
            except Exception:
                pass
        if fb_supp:
            supplier_name = fb_supp
        elif state.get("grounding_errors") or any(
            "error" in entry.lower() for entry in state.get("audit_log", [])
        ):
            supplier_name = "(extraction failed)"

    triggered_dicts: list[dict[str, str]] = []
    if dec:
        for r in dec.triggered_rules:
            triggered_dicts.append(
                {
                    "rule_id": r.rule_id,
                    "severity": r.severity.value,
                    "message": r.message,
                    "evidence_quote": r.evidence_quote,
                }
            )

    # If verdict is Needs a person to check and triggered_dicts is empty, find cause from audit_log
    if system_verdict == "Needs a person to check" and not triggered_dicts:
        cause = None
        audit_log = state.get("audit_log") or []
        for entry in reversed(audit_log):
            if "LLM failed:" in entry or "error:" in entry.lower() or "exception" in entry.lower():
                cause = entry.split("] ", 1)[-1] if "] " in entry else entry
                break
        if not cause:
            cause = "Unverifiable extraction or grounding failure"
        triggered_dicts.append(
            {
                "rule_id": "RULE_REV_11_UNVERIFIABLE_FIELD",
                "severity": "REVIEW",
                "message": cause,
                "evidence_quote": "N/A",
            }
        )

    extractor_used = state.get("extractor_used", "none")
    # If any error in audit log or grounding errors, ensure extractor_used reflects that
    if (
        state.get("grounding_errors")
        and "error" not in extractor_used
        and "failed" not in extractor_used
    ):
        extractor_used = "error: see audit log"

    return {
        "pdf": pdf_path,
        "supplier": supplier_name,
        "item": item_code,
        "system_verdict": system_verdict,
        "final_verdict": final_verdict,
        "reviewer_note": reviewer_note,
        "extractor_used": extractor_used,
        "triggered_rules": triggered_dicts,
        "audit_log": state.get("audit_log", []),
    }


def node_report(state: PipelineState) -> dict[str, Any]:
    """Build structured report preserving system verdict and recording reviewer resolution."""
    report = _build_report_payload(state)
    _log_event(
        state,
        f"Report generated: system_verdict={report['system_verdict']}, final_verdict={report['final_verdict']}",
    )
    return {
        "report": report,
        "audit_log": state.get("audit_log", []),
    }


# ---------------------------------------------------------------------------
# Graph Builder
# ---------------------------------------------------------------------------


def build_supplier_checker_graph(
    checkpointer: Any = None,
    llm_client: LLMClient | None = None,
) -> Any:
    """Build the fixed linear LangGraph pipeline.

    Nodes: ingest -> extract -> verify -> compare -> rules -> decide -> (conditional) human_review -> report
    """
    graph = StateGraph(PipelineState)

    def extract_with_client(state: PipelineState) -> dict[str, Any]:
        if llm_client is not None and not state.get("llm_client"):
            merged_state = dict(state)
            merged_state["llm_client"] = llm_client
            return node_extract(merged_state)  # type: ignore[arg-type]
        return node_extract(state)

    graph.add_node("ingest", node_ingest)
    graph.add_node("extract", extract_with_client)
    graph.add_node("verify", node_verify)
    graph.add_node("compare", node_compare)
    graph.add_node("rules", node_rules)
    graph.add_node("decide", node_decide)
    graph.add_node("human_review", node_human_review)
    graph.add_node("report", node_report)

    graph.add_edge(START, "ingest")
    graph.add_edge("ingest", "extract")
