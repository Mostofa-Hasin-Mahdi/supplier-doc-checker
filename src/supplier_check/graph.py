"""LangGraph pipeline for supplier document checking.

Nodes:
ingest -> extract -> verify -> compare -> rules -> decide -> (conditional) human_review -> report

- extract node modes: auto | fallback | llm | both
  - auto: use both with reconciliation if GEMINI_API_KEY is present; else fallback only.
- Exceptions in any node are caught, appended to audit_log, and route safely to "Needs a person to check".
- human_review uses LangGraph interrupt() with a checkpointer (SqliteSaver or MemorySaver).
- report node builds a structured PipelineReport.
"""

